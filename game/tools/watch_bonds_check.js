// node tools/watch_bonds_check.js : checks the relationship rules from the storyboard.
const B = require('../js/watch-bonds.js');
let bad = 0; const ok = (c, m) => { if (!c) { bad++; console.log('FAIL', m); } };
const ties = { hobb: { warm: ['mira', 'odu'], cool: ['doug'] }, odu: { warm: ['hobb', 'doug'] }, mira: { warm: ['wen'] } };
const b = B.create(1);
ok(B.trust(b, 'hobb') === 15 && B.trust(b, 'mira') === 80 && B.trust(b, 'kai') === 80 && B.trust(b, 'dutch') === 70, 'start values: the party trusts her, locals barely know her');
B.chat(b, 'hobb'); B.chat(b, 'hobb'); ok(B.trust(b, 'hobb') === 17, 'one chat bonus per day');
B.newDay(b, 2); B.chat(b, 'hobb'); ok(B.trust(b, 'hobb') === 19, 'chat bonus again next day');
let r = B.refer(b, ties, 'hobb', 'mira'); ok(r.tie === 'warm' && r.score === 19 && r.band === 'low', 'low trust in you limits a warm referral');
B.add(b, 'hobb', 61);
r = B.refer(b, ties, 'hobb', 'mira'); ok(r.score === 80 && r.band === 'high', 'warm caps at 80');
r = B.refer(b, ties, 'hobb', 'wen'); ok(r.tie === 'neutral' && r.score === 50 && r.band === 'mid', 'neutral caps at 50');
r = B.refer(b, ties, 'hobb', 'doug'); ok(r.band === 'deny' && r.score === 0, 'cool is an explicit deny despite high trust');
B.add(b, 'odu', 'trust');
ok(B.vouchers(b, ties, 'hobb', 'doug', ['odu', 'mira']).join() === 'odu', 'odu can vouch (warm to both)');
B.shift(b, 'hobb', 'doug', 'warm'); ok(B.refer(b, ties, 'hobb', 'doug').band !== 'deny', 'gossip mends a tie for the day');
B.newDay(b, 3); ok(B.refer(b, ties, 'hobb', 'doug').band === 'deny', 'tie change lasts one day');
ok(B.price(b, 'hobb', 15) === 12 && B.price(b, 'odu', 15) === 15, 'discount only at 60+ in shops');
ok(B.perks(b, 'hobb').indexOf('second-try') >= 0 && B.perks(b, 'pell').length === 0 && B.perks(b, 'mira').indexOf('secret-gossip') >= 0, 'perk thresholds');
B.add(b, 'x', 500); ok(B.trust(b, 'x') === 100, 'clamped to 100');
console.log(bad ? bad + ' failed' : 'watch bonds: all ok'); process.exit(bad ? 1 : 0);
